/** Cards whose citation no reviewer has confirmed. A non-empty result blocks release. */
export function unverifiedCards(): EducationTopic[] {
  return (Object.keys(CREDIT_EDUCATION) as EducationTopic[]).filter(
    (topic) => !CREDIT_EDUCATION[topic].source.verified,
  );
}

/** Cards whose review has gone stale. A non-empty result blocks the release gate. */
export function staleCards(now = new Date()): EducationTopic[] {
  const cutoff = now.getTime() - REVIEW_MAX_AGE_DAYS * 24 * 60 * 60 * 1000;
  return (Object.keys(CREDIT_EDUCATION) as EducationTopic[]).filter(
    (topic) => Date.parse(CREDIT_EDUCATION[topic].source.reviewedAt) < cutoff,
  );
}
