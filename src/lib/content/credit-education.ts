/**
 * Source-backed credit education. US only, and only three topics.
 *
 * The boundary this file defends: EDUCATION is not ELIGIBILITY. Nothing here
 * tells a student whether they qualify for a product, and nothing promises a
 * score will rise. Where we have not reviewed a source, the honest answer is
 * that we do not know, and the tool returns that instead of improvising.
 *
 * Every card names the primary source it rests on and the date it was reviewed.
 * A card whose review date is older than REVIEW_MAX_AGE_DAYS must be re-checked
 * before release; `staleCards()` is what the release gate calls.
 */
export type EducationTopic =
  | 'credit_reports'
  | 'correcting_errors'
  | 'responsible_repayment'
  | 'starting_without_history';

export interface EducationCard {
  readonly title: string;
  readonly jurisdiction: 'US';
  /** Short, factual statements that the named source supports. */
  readonly points: readonly string[];
  readonly source: {
    readonly publisher: string;
    readonly url: string;
    readonly reviewedAt: string;
    /**
     * TRUE only once a reviewer has opened this exact URL and confirmed it supports
     * every point above. A search snippet does not count. While this is false the
     * card is served with an explicit unverified label, and the release gate
     * reports it, because an unchecked citation is worse than no citation.
     */
    readonly verified: boolean;
  };
  /** What this card deliberately does NOT tell the reader. */
  readonly limits: string;
}

